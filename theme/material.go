package theme

import (
	giofont "gioui.org/font"
	"gioui.org/font/gofont"
	"gioui.org/text"
)

// MaterialLight returns a Material 3 baseline light theme.
//
// Color values follow Google's Material 3 baseline scheme published at
// https://m3.material.io/styles/color/the-color-system/color-roles —
// purple primary on a near-white surface.
func MaterialLight() *Theme {
	return &Theme{
		Palette: Palette{
			Primary:          NRGBA(0x67, 0x50, 0xA4, 0xFF),
			PrimaryLight:     NRGBA(0xEA, 0xDD, 0xFF, 0xFF),
			PrimaryDark:      NRGBA(0x4F, 0x37, 0x8B, 0xFF),
			OnPrimary:        NRGBA(0xFF, 0xFF, 0xFF, 0xFF),
			Secondary:        NRGBA(0x62, 0x5B, 0x71, 0xFF),
			OnSecondary:      NRGBA(0xFF, 0xFF, 0xFF, 0xFF),
			Background:       NRGBA(0xFF, 0xFB, 0xFE, 0xFF),
			Surface:          NRGBA(0xFF, 0xFB, 0xFE, 0xFF),
			SurfaceVariant:   NRGBA(0xE7, 0xE0, 0xEC, 0xFF),
			OnBackground:     NRGBA(0x1C, 0x1B, 0x1F, 0xFF),
			OnSurface:        NRGBA(0x1C, 0x1B, 0x1F, 0xFF),
			Error:            NRGBA(0xB3, 0x26, 0x1E, 0xFF),
			OnError:          NRGBA(0xFF, 0xFF, 0xFF, 0xFF),
			Success:          NRGBA(0x2E, 0x7D, 0x32, 0xFF),
			Warning:          NRGBA(0xED, 0x6C, 0x02, 0xFF),
			Info:             NRGBA(0x02, 0x88, 0xD1, 0xFF),
			Outline:          NRGBA(0x79, 0x74, 0x7E, 0xFF),
			OutlineVariant:   NRGBA(0xCA, 0xC4, 0xD0, 0xFF),
			InverseSurface:   NRGBA(0x31, 0x30, 0x33, 0xFF),
			InverseOnSurface: NRGBA(0xF4, 0xEF, 0xF4, 0xFF),
			Scrim:            NRGBA(0x00, 0x00, 0x00, 0x66),
		},
		Typo:        defaultTypography(),
		Space:       defaultSpacing(),
		Corner:      defaultCornerRadius(),
		Elev:        defaultElevation(),
		Shaper:      text.NewShaper(text.WithCollection(gofont.Collection())),
		DefaultFont: giofont.Font{},
	}
}

